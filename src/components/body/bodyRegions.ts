// Duas figuras: masculina (public/body/corpo.webp) e feminina (public/body/corpo-feminino.webp).
// Cada uma tem as próprias coordenadas, porque o corpo ocupa lugares diferentes em cada imagem.
//
// Masculina: coordenadas em pixels da imagem (1024 x 765).
// Feminina: a imagem foi recortada só na área do corpo e as coordenadas estão em 388 x 676
// (o arquivo tem o dobro disso, 776 x 1352, para ficar nítido em telas de alta densidade).
//
// As formas foram extraídas das próprias imagens: o corpo foi separado do fundo pelo brilho,
// a silhueta foi cortada em braços, pernas, cabeça e tronco, e cada contorno foi simplificado
// (Douglas-Peucker) e suavizado em curvas. Se trocar uma imagem, refaça as formas dela.
export type BodyFigure = 'male' | 'female';

export type RegionShape =
  | { kind: 'ellipse'; cx: number; cy: number; rx: number; ry: number }
  | { kind: 'path'; d: string };

export interface BodyRegionDef {
  id: BodyRegion;
  shapes: RegionShape[];
  // Onde fica o marcador com o ícone do nível. Em região pequena ele fica ao lado,
  // ligado à forma por uma linha (leader), para não cobrir nada.
  marker: { x: number; y: number; leader?: { x: number; y: number } };
  // Aumenta a área de clique de formas pequenas sem mudar o desenho.
  padHit?: boolean;
  // Áreas de clique extras, invisíveis e sem sobreposição com as outras regiões (cabeça).
  hit?: string[];
}

